#!/usr/bin/env python3
"""Generate docs/UNITS.md from the JSON balance data (effective values after faction multipliers)."""
import json, os
D = 'MeridianCore/Sources/MeridianCore/Data/'
load = lambda f: json.load(open(D + f))
factions = {f['faction']: f for f in load('factions.json')}
units = load('units_humans.json') + load('units_machines.json') + load('units_aliens.json')
buildings = load('buildings.json'); upgrades = load('upgrades.json'); rules = load('rules.json')
names = {b['id']: b['name'] for b in buildings}; names.update({u['id']: u['name'] for u in upgrades})

def cost(c): return " / ".join(f"{c[k]}{k[0].upper()}" for k in ('iron', 'wood', 'gold') if c[k])
out = ["# Meridian: Unit, Building and Upgrade Reference", "",
       "Generated by `tools/gen_unit_docs.py` from `MeridianCore/Sources/MeridianCore/Data/*.json`. "
       "HP and build time include faction multipliers (Lattice ×1.35 HP / ×1.4 time, Brood ×0.8 HP / ×0.75 time). "
       "Costs are Iron / Wood / Gold. Damage model: `max(25% of raw, raw × tag bonus − armor)`.", ""]
for fk, f in factions.items():
    out += [f"## {f['name']} ({fk}) — {f['tagline']}", "", f['description'], "",
            "| Unit | Role | HP | Armor | Weapon (dmg / interval / range, targets) | Speed | Cost | Build s | Produced at | Requires | Abilities |",
            "|---|---|---|---|---|---|---|---|---|---|---|"]
    for u in [u for u in units if u['faction'] == fk]:
        w = u.get('weapon')
        if w:
            tgt = "G+A" if w['targetsGround'] and w['targetsAir'] else ("Air" if w['targetsAir'] else "Ground")
            ws = f"{w['damage']} / {w['interval']}s / {w['range']} {tgt}"
            if w.get('splash'): ws += f", splash {w['splash']}"
            if w.get('minRange'): ws += f", min {w['minRange']}"
            if w.get('bonus'): ws += ", " + ", ".join(f"×{v} vs {k}" for k, v in w['bonus'].items())
        else: ws = "—"
        hp = round(u['hp'] * f['hpMult']); bt = round(u['buildTime'] * f['buildTimeMult'], 1)
        ab = ", ".join(u.get('abilities', [])) or "—"
        if u.get('batch'): ab += f" (spawns ×{u['batch']})"
        req = ", ".join(names.get(r, r) for r in u['requires']) or "—"
        out.append(f"| **{u['name']}** | {u['role']} | {hp} | {u['armor']} | {ws} | {u['speed']} | {cost(u['cost'])} | {bt} | {u['producedAt']} | {req} | {ab} |")
    out += ["", "**Counters and weaknesses**", ""]
    for u in [u for u in units if u['faction'] == fk]:
        out.append(f"- **{u['name']}** — {u['description']} Strong vs: {u['strongVs']} Weak vs: {u['weakVs']}")
    out += ["", "**Buildings**", "", "| Building | Kind | HP | Armor | Size | Cost | Build s | Requires | Notes |", "|---|---|---|---|---|---|---|---|---|"]
    for b in [b for b in buildings if b['faction'] == fk]:
        hp = round(b['hp'] * f['hpMult']); bt = round(b['buildTime'] * f['buildTimeMult'], 1)
        req = ", ".join(names.get(r, r) for r in b['requires']) or "—"
        note = b['description'] + (f" Weapon {b['weapon']['damage']} dmg, range {b['weapon']['range']}." if b.get('weapon') else "")
        out.append(f"| **{b['name']}** | {b['kind']} | {hp} | {b['armor']} | {b['size']}×{b['size']} | {cost(b['cost'])} | {bt} | {req} | {note} |")
    out += ["", "**Upgrades**", "", "| Upgrade | Tier | At | Cost | Time | Requires | Effect |", "|---|---|---|---|---|---|---|"]
    for g in [g for g in upgrades if g['faction'] == fk]:
        req = ", ".join(names.get(r, r) for r in g['requires']) or "—"
        ex = f" Exclusive with {names[g['exclusiveWith']]}." if g.get('exclusiveWith') else ""
        out.append(f"| **{g['name']}** | {g['tier']} | {g['researchedAt']} | {cost(g['cost'])} | {g['time']}s | {req} | {g['description']}{ex} |")
    out.append("")
t = rules['territory']; c = rules['combat']; e = rules['economy']
out += ["## Global rules", "",
        f"- Unit cap: **{c['unitCap']} actual units** per player (no weighted supply).",
        f"- Workers carry Iron {e['carry'][0]} / Gold {e['carry'][1]} / Wood {e['carry'][2]} per trip; gather time {e['gatherTime']} s.",
        f"- Start: {e['startWorkers']} workers, {e['startIron']} iron, {e['startWood']} wood.",
        f"- Sites: capture radius {t['captureRadius']}, {t['captureTime']} s for one unit (up to ×{t['maxCaptureMult']} with more), income per second {t['income']} (iron/gold/wood), vision {t['vision']}.",
        f"- Installations ({cost(t['installCost'])}): Extractor ×{t['extractorIncomeMult']} income · Watchpost vision {t['watchVision']} + detection · Bulwark turret {t['bulwarkHp']} HP.",
        f"- Dominance victory: hold ≥{int(t['dominanceFraction']*100)}% of sites for {t['dominanceSeconds']} s; countdown can only run after {t['dominanceStart']//60:.0f}:00.",
        f"- Towers: must be within {c['towerBuildRadius']} tiles of an HQ, depot or forward structure (or near an owned site); each additional tower costs +{int(c['towerCostGrowth']*100)}%.",
        f"- Machine network link: ≥{c['networkLinkMinNeighbors']} machine allies within {c['networkLinkRadius']} tiles or inside a network structure's field → −{int(c['networkDamageReduction']*100)}% damage taken, +{int(c['networkDamageBonus']*100)}% damage dealt (non-stacking).",
        f"- Alien Bloom: out of combat for {c['outOfCombatSeconds']} s → regenerate {c['alienRegenFlat']} + {c['alienRegenPercent']*100:.0f}% max HP per second; +{int(t['alienSpeedBonus']*100)}% speed.",
        "- Human staging: units inside HQ / Forward Post / owned-site staging zones deal +10% damage; Forward Posts and sites repair units.", ""]
os.makedirs('docs', exist_ok=True)
open('docs/UNITS.md', 'w').write("\n".join(out))
print("wrote docs/UNITS.md", len(out), "lines")
